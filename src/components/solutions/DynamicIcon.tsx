type DynamicIconProps = {
  name: string
  className?: string
}

export function DynamicIcon({ name, className }: DynamicIconProps): React.ReactNode {
  const Icon = iconMap[name]
  if (!Icon) return null
  return <Icon className={className} aria-hidden />
}
